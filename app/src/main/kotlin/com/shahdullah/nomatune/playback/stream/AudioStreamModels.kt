package com.shahdullah.nomatune.playback.stream

import com.shahdullah.nomatune.constants.AudioQuality
import com.shahdullah.nomatune.innertube.PlaybackAuthState

enum class StreamPurpose {
    PLAYBACK,
    DOWNLOAD,
}

enum class StreamSource {
    YOUTUBEI,
    EXTERNAL,
}

data class AudioStreamRequest(
    val mediaId: String,
    val playlistId: String? = null,
    val quality: AudioQuality,
    val networkMetered: Boolean,
    val purpose: StreamPurpose,
    val authState: PlaybackAuthState,
    val pinnedFormatId: Int? = null,
    val requiresSongMetadata: Boolean = false,
    // Kept for parity with the upstream resolver contract; NomaTune has no
    // audio-module system, so this is accepted and ignored.
    val allowModules: Boolean = true,
)

data class ResolvedAudioStream(
    val url: String,
    val requestHeaders: Map<String, String>,
    val formatId: Int,
    val mimeType: String,
    val codecs: String,
    val bitrate: Int,
    val sampleRate: Int?,
    val contentLength: Long,
    val expiresAtMs: Long,
    val authFingerprint: String,
    val source: StreamSource,
    val runtimeVersion: String? = null,
    val title: String? = null,
    val durationSeconds: Int? = null,
    val thumbnailUrl: String? = null,
    val loudnessDb: Double? = null,
    val perceptualLoudnessDb: Double? = null,
    val playbackTrackingUrl: String? = null,
    val gvsPoTokenBinding: GvsPoTokenBinding? = null,
    val gvsPoTokenMinterGeneration: Long? = null,
)
